class Post(unittest.TestCase):
    def setUp(self):
        self.dir = Path(tempfile.mkdtemp())
        state = {
            "local": False,
            "pr_id": "PR",
            "head": "abc",
            "postable": True,
            "url": "https://github.com/o/r/pull/1",
        }
        (self.dir / "state.json").write_text(json.dumps(state))
        comment = {"path": "a.go", "subjectType": "LINE", "line": 3, "body": "x"}
        (self.dir / "resolved.json").write_text(json.dumps([comment]))
        patcher = mock.patch.object(rh, "require_gh")
        patcher.start()
        self.addCleanup(patcher.stop)

    def post(
        self,
        head: str = "abc",
        pending=None,
        final_state: str = "PENDING",
        pr_state: str = "OPEN",
        pending_comments=(),
    ):
        calls = []

        def graphql(query, **variables):
            calls.append(query)
            if query == rh.ADD_REVIEW:
                return {"addPullRequestReview": {"pullRequestReview": {"id": "NEW"}}}
            if query == rh.ADD_THREAD:
                return {"addPullRequestReviewThread": {"thread": {"id": "T"}}}
            return {"node": {"state": final_state, "comments": {"nodes": []}}}

        info = {
            "headRefOid": head,
            "state": pr_state,
            "pending": pending,
            "pending_comments": list(pending_comments),
        }
        patch_info = mock.patch.object(rh, "pr_info", return_value=info)
        patch_graphql = mock.patch.object(rh, "graphql", side_effect=graphql)
        with patch_info, patch_graphql, redirect_stdout(io.StringIO()):
            rh.cmd_post(Namespace(dir=str(self.dir)))
        return calls

    def test_creates_pending_review_and_adds_threads(self):
        calls = self.post()
        self.assertEqual(calls[:2], [rh.ADD_REVIEW, rh.ADD_THREAD])

    def test_reuses_existing_pending_review(self):
        calls = self.post(pending={"id": "OLD", "commit": {"oid": "abc"}})
        self.assertNotIn(rh.ADD_REVIEW, calls)

    def test_refuses_when_head_moved(self):
        with self.assertRaises(rh.Failure):
            self.post(head="def")

    def test_fails_loudly_when_not_pending(self):
        with self.assertRaises(rh.Failure):
            self.post(final_state="COMMENTED")

    def test_refuses_closed_pr(self):
        with self.assertRaises(rh.Failure):
            self.post(pr_state="MERGED")

    def test_rerun_skips_already_added_comments(self):
        added = {"path": "a.go", "line": 3, "originalLine": 3, "body": "x"}
        calls = self.post(pending={"id": "OLD", "commit": {"oid": "abc"}}, pending_comments=[added])
        self.assertNotIn(rh.ADD_THREAD, calls)


