class LocalRepo(unittest.TestCase):
    """Runs git against a throwaway repository."""

    def setUp(self):
        self.repo = Path(tempfile.mkdtemp())
        git_in(self.repo, "init", "-q", "-b", "main")
        git_in(self.repo, "config", "user.email", "t@example.com")
        git_in(self.repo, "config", "user.name", "t")
        git_in(self.repo, "config", "commit.gpgsign", "false")
        self.commit("docs/reviewer-guide.md", "base rules\n")
        cwd = Path.cwd()
        os.chdir(self.repo)
        self.addCleanup(os.chdir, cwd)

    def commit(self, path: str, text: str) -> None:
        (self.repo / path).parent.mkdir(parents=True, exist_ok=True)
        (self.repo / path).write_text(text)
        git_in(self.repo, "add", path)
        git_in(self.repo, "commit", "-q", "-m", path)

    def test_newest_base_wins_over_stale_main(self):
        stale = git_in(self.repo, "rev-parse", "HEAD").strip()
        self.commit("upstream.go", "x\n")
        git_in(self.repo, "update-ref", "refs/remotes/origin/main", "HEAD")
        git_in(self.repo, "checkout", "-q", "-b", "feature")
        git_in(self.repo, "branch", "-f", "main", stale)
        self.commit("feature.go", "y\n")
        upstream = git_in(self.repo, "rev-parse", "origin/main").strip()
        self.assertEqual(rh.pick_base(None, None), (upstream, "origin/main"))
        self.assertEqual(rh.pick_base("main", None), (stale, "main"))

    def test_local_diff_ignores_user_diff_config(self):
        git_in(self.repo, "checkout", "-q", "-b", "feature")
        self.commit("docs/reviewer-guide.md", "changed rules\n")
        git_in(self.repo, "config", "diff.noprefix", "true")
        with mock.patch.object(rh, "local_pr", return_value=None):
            source = rh.local_source(None)
        self.assertEqual([f.path for f in source.files], ["docs/reviewer-guide.md"])
        out = Path(tempfile.mkdtemp())
        (out / "docs").mkdir()
        fallback = mock.patch.object(rh, "raw_file", side_effect=AssertionError("no network"))
        with fallback, mock.patch.object(rh, "DOC_PATHS", ("docs/reviewer-guide.md",)):
            rh.write_docs(out, source.read_base_blobs)
        self.assertEqual((out / "docs/reviewer-guide.md").read_text(), "base rules\n")


