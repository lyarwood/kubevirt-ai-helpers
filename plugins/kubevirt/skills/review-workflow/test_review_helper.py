class ParseDiff(unittest.TestCase):
    def test_new_file(self):
        (f,) = rh.parse_diff(NEW_FILE)
        self.assertEqual(f.path, "pkg/new.go")
        self.assertEqual(f.added, [(1, "package pkg"), (2, ""), (3, "func A() {}")])
        self.assertTrue(f.executable)

    def test_line_numbers_skip_removed_lines(self):
        (f,) = rh.parse_diff(MODIFIED)
        self.assertEqual(f.lines[11], (0, "\tb := 3", 12, True))
        self.assertEqual(f.lines[12], (0, "\treturn a + b", 12, False))
        self.assertEqual(f.lines[41], (1, "\t\treturn err", 41, True))
        self.assertEqual(f.lines[42], (1, "\t}", 41, False))
        self.assertNotIn(43, f.lines)
        self.assertEqual(f.removed, ["\tb := 2"])

    def test_deleted_file(self):
        text = (
            "diff --git a/old.go b/old.go\ndeleted file mode 100644\n"
            "--- a/old.go\n+++ /dev/null\n@@ -1,2 +0,0 @@\n-package x\n-\n"
        )
        (f,) = rh.parse_diff(text)
        self.assertTrue(f.deleted)
        self.assertEqual(f.lines, {})

    def test_rename_uses_new_path(self):
        text = (
            "diff --git a/a.go b/b.go\nsimilarity index 90%\nrename from a.go\n"
            "rename to b.go\n--- a/a.go\n+++ b/b.go\n@@ -1 +1 @@\n-x\n+y\n"
        )
        (f,) = rh.parse_diff(text)
        self.assertEqual((f.path, f.old_path), ("b.go", "a.go"))

    def test_deleted_without_mode_line(self):
        text = "diff --git a/old.go b/old.go\n--- a/old.go\n+++ /dev/null\n@@ -1 +0,0 @@\n-x\n"
        self.assertTrue(rh.parse_diff(text)[0].deleted)

    def test_binary(self):
        text = "diff --git a/x.png b/x.png\nBinary files a/x.png and b/x.png differ\n"
        self.assertTrue(rh.parse_diff(text)[0].binary)

    def test_unicode_line_separator_stays_in_line(self):
        (f,) = rh.parse_diff(diff_of("a.go", "@@ -0,0 +1,2 @@\n+a\u2028b\n+c\n"))
        self.assertEqual(f.added, [(1, "a\u2028b"), (2, "c")])


class Classification(unittest.TestCase):
    def test_categories(self):
        self.assertEqual(rh.category("vendor/k8s.io/api/x.go"), "vendor")
        self.assertEqual(rh.category("tools/vendor/k8s.io/api/x.go"), "vendor")
        self.assertEqual(rh.category("pkg/a/zz_generated.deepcopy.go"), "generated")
        self.assertEqual(rh.category("staging/x/apitesting/testdata/a.json"), "api-artifacts")
        self.assertIsNone(rh.category("pkg/x/testdata/a.yaml"))
        self.assertIsNone(rh.category("pkg/a/BUILD.bazel"))
        self.assertIsNone(rh.category("hack/generated.sh"))
        self.assertIsNone(rh.category("go.mod"))
        self.assertIsNone(rh.category("pkg/a/types.go"))

    def test_generated_needs_header(self):
        header = "// Code generated by MockGen. DO NOT EDIT.\npackage a\n"
        new = "new file mode 100644\n"
        files = rh.parse_diff(
            diff_of("pkg/a/generated_mock_a.go", "@@ -0,0 +1,2 @@\n+// x\n+package a\n", header=new)
            + diff_of("pkg/b/generated_mock_b.go", "@@ -50,1 +50,1 @@\n-x\n+y\n")
            # only the first line is in the diff, the header comes later
            + diff_of("pkg/c/generated_mock_c.go", "@@ -1,1 +1,1 @@\n-// old\n+// new\n")
        )
        blobs = {
            "pkg/b/generated_mock_b.go": header,
            "pkg/c/generated_mock_c.go": "// x\n" + header,
        }
        generated = rh.generated_go_files(files, lambda paths: {p: blobs[p] for p in paths})
        self.assertEqual(generated, {"pkg/b/generated_mock_b.go", "pkg/c/generated_mock_c.go"})
        hints = rh.consistency_hints(files, generated, {})
        self.assertTrue(any("generated_mock_a.go: named like" in h for h in hints))

    def test_split_threshold_and_flags(self):
        big = "@@ -0,0 +1,1 @@\n+" + "x" * rh.SPLIT_MIN_BYTES + "\n"
        files = rh.parse_diff(
            diff_of("go.sum", big) + diff_of("vendor/m/a.go", big) + diff_of("pkg/a.go", big)
        )
        split = rh.split_files(files, set(), {"vendor/m/a.go"}, "")
        self.assertEqual([f.path for f in split.moved], ["go.sum"])
        self.assertEqual(rh.split_files(files, set(), set(), "untrusted").moved, [])
        named = rh.parse_diff(diff_of("src/generated/a.ts", big) + diff_of("old_generated.go", big))
        named[1].deleted = True
        moved = rh.split_files(named, set(), set(), "").moved
        self.assertEqual([f.path for f in moved], ["old_generated.go"])
        small = rh.parse_diff(diff_of("go.sum", "@@ -0,0 +1,1 @@\n+x\n"))
        self.assertEqual(rh.split_files(small, set(), set(), "").moved, [])

    def test_priority_order(self):
        paths = ["tests/a.go", "cmd/a.go", "pkg/a.go", "staging/src/kubevirt.io/api/a.go"]
        self.assertEqual(sorted(paths, key=rh.priority), [paths[3], paths[2], paths[1], paths[0]])
        self.assertEqual(rh.priority("tools/vendor/k8s.io/api/a.go"), 2)

    def test_untrusted_authors_get_full_diff(self):
        self.assertTrue(rh.full_diff_reason(False, "FIRST_TIME_CONTRIBUTOR"))
        self.assertTrue(rh.full_diff_reason(True, "MEMBER"))
        self.assertEqual(rh.full_diff_reason(False, "MEMBER"), "")


