class RemoteDiff(unittest.TestCase):
    def remote_diff(self, gh_responses, head=HEAD):
        patch_gh = mock.patch.object(rh, "gh", side_effect=gh_responses)
        patch_graphql = mock.patch.object(rh, "graphql", return_value=head)
        with patch_gh, patch_graphql:
            return rh.remote_diff(PR)

    def test_only_too_large_falls_back_to_files(self):
        with self.assertRaises(rh.Failure):
            self.remote_diff(rh.Failure("gh: denied (HTTP 401)"))
        items = [
            {
                "filename": "a.go",
                "status": "modified",
                "changes": 2,
                "patch": "@@ -1 +1 @@\n-a\n+b",
            },
            {"filename": "d.go", "status": "removed", "changes": 1, "patch": "@@ -1 +0,0 @@\n-x"},
            {"filename": "n.go", "previous_filename": "o.go", "status": "renamed", "changes": 0},
        ]
        too_large = rh.Failure("gh: diff too large (HTTP 406)")
        diff, gaps = self.remote_diff([too_large, "\n".join(map(json.dumps, items))])
        files = rh.parse_diff(diff)
        self.assertEqual([f.path for f in files], ["a.go", "d.go", "n.go"])
        self.assertEqual(files[0].added, [(1, "b")])
        self.assertTrue(files[1].deleted)
        self.assertTrue(any("executable bits not checked" in g for g in gaps))
        self.assertTrue(any("1 of 4 changed files missing" in g for g in gaps))
