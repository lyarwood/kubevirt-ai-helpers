HUNKS = {
    "a.go": [
        [10, 0, "func A() {"],
        [11, 0, "\treturn nil"],
        [12, 0, "}"],
        [40, 1, "func B() {"],
        [41, 1, "\treturn nil"],
        [42, 1, "}"],
    ]
}


class Resolve(unittest.TestCase):
    def resolve(self, **finding):
        return rh.resolve_finding({"path": "a.go", "body": "Why?", **finding}, HUNKS)

    def error(self, **finding):
        with self.assertRaises(rh.Unresolved) as context:
            self.resolve(**finding)
        return str(context.exception)

    def test_unique_anchor(self):
        self.assertEqual(self.resolve(anchor="func B")["line"], 40)

    def test_ambiguous_anchor(self):
        self.assertIn("L11, L41", self.error(anchor="return nil"))
        self.assertEqual(self.resolve(anchor="return nil", line_hint=39)["line"], 41)

    def test_outside_hunks(self):
        self.assertIn("not found", self.error(anchor="func C"))
        self.assertIn("not changed", self.error(path="b.go", anchor="x"))

    def test_multi_line_stays_in_hunk(self):
        comment = self.resolve(anchor="func A", end_anchor="}")
        self.assertEqual((comment["startLine"], comment["line"]), (10, 12))
        self.assertIn("L11-L12", self.error(anchor="func A", end_anchor="func B"))

    def test_file_level(self):
        comment = self.resolve(anchor=None)
        self.assertEqual(comment["subjectType"], "FILE")
        self.assertNotIn("line", comment)

    def test_body_lint(self):
        self.assertEqual(rh.lint_body("Use `--flag`?"), [])
        self.assertEqual(len(rh.lint_body("[NIT] a -- b \u2014 c")), 3)
        self.assertEqual(rh.lint_body("Pass --no-split here?\n\n---\nok"), [])
        self.assertEqual(len(rh.lint_body("a-- b")), 1)

    def test_duplicate_warning(self):
        findings = [{"path": "a.go", "anchor": "func A", "body": "x"}]
        _, errors, warnings = rh.resolve_findings(findings, HUNKS, [["a.go", 10]])
        self.assertEqual(errors, [])
        self.assertEqual(len(warnings), 1)
        file_level = [{"path": "a.go", "anchor": None, "body": "x"}]
        self.assertEqual(rh.resolve_findings(file_level, HUNKS, [["a.go", None]])[2], [])


