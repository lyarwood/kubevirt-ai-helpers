class Vendor(unittest.TestCase):
    def files(self, *paths: str):
        return rh.parse_diff(
            MODULES_TXT + "".join(diff_of(p, "@@ -1 +1 @@\n-a\n+b\n") for p in paths)
        )

    def test_module_changes_with_replace_lines(self):
        changes = rh.module_changes(self.files())
        self.assertEqual(set(changes), {"vendor/k8s.io/api", "vendor/github.com/new/mod"})
        self.assertIsNone(changes["vendor/github.com/new/mod"][0])

    def test_hand_edit_detection(self):
        files = self.files(
            "vendor/k8s.io/api/core/v1/types.go",
            "vendor/github.com/golang/protobuf/ptypes/any.go",
            "vendor/github.com/other/mod/x.go",
        )
        hits = rh.vendor_hand_edits(files, rh.module_changes(files))
        self.assertEqual([h.path for h in hits], ["vendor/github.com/other/mod/x.go"])

    def test_nested_vendor_and_license_files(self):
        modules_txt = diff_of(
            "api/vendor/modules.txt",
            "@@ -1,2 +1,2 @@\n-# k8s.io/utils v1\n+# k8s.io/utils v2\n-k8s.io/x/y/z\n",
        )
        change = "@@ -1 +1 @@\n-a\n+b\n"
        files = rh.parse_diff(
            modules_txt
            + diff_of("api/vendor/k8s.io/utils/a.go", change)
            + diff_of("api/vendor/k8s.io/x/LICENSE", change)
            + diff_of("api/vendor/k8s.io/x.go", change)
            + diff_of("api/vendor/k8s.io/other/b.go", change)
            + diff_of("api/vendor/k8s.io/gone/c.go", change, header="deleted file mode 100644\n")
        )
        hits = rh.vendor_hand_edits(files, rh.module_changes(files))
        self.assertEqual(
            [h.path for h in hits], ["api/vendor/k8s.io/x.go", "api/vendor/k8s.io/other/b.go"]
        )

    def test_non_go_vendor_is_not_a_hand_edit(self):
        files = rh.parse_diff(diff_of("vendor/composer/autoload.php", "@@ -1 +1 @@\n-a\n+b\n"))
        self.assertEqual(rh.vendor_hand_edits(files, {}), [])

    def test_new_module_hint(self):
        files = self.files()
        hints = rh.consistency_hints(files, set(), rh.module_changes(files))
        self.assertTrue(any("github.com/new/mod" in h for h in hints))


class Scan(unittest.TestCase):
    def hits(self, path: str, line: str, deep: bool = False):
        files = rh.parse_diff(diff_of(path, f"@@ -0,0 +1,1 @@\n+{line}\n"))
        return [h.kind for h in rh.scan(files, {path} if deep else set())]

    def test_hidden_characters(self):
        self.assertIn("hidden or bidi Unicode character", self.hits("a.go", "x\u202ey"))

    def test_blob(self):
        self.assertIn("long base64 or hex blob", self.hits("a.yaml", "k: " + "A" * 250))

    def test_non_ascii_only_flagged_outside_strings(self):
        self.assertEqual(self.hits("a.go", 'x := "gr\u00fc\u00df"'), [])
        self.assertIn("non-ASCII in Go code", self.hits("a.go", "var gr\u00fc\u00df = 1"))

    def test_imports_in_generated_code(self):
        new_import = ["new import in generated/vendored code"]
        self.assertEqual(self.hits("a.go", '\t"fmt"', deep=True), new_import)
        self.assertEqual(self.hits("a.go", '\t"os/exec"'), [])

    def test_executable_bit_on_scripts_is_fine(self):
        def hits(path, line):
            diff = diff_of(path, f"@@ -0,0 +1,1 @@\n+{line}\n", header="new mode 100755\n")
            return [h.kind for h in rh.scan(rh.parse_diff(diff), set())]

        self.assertEqual(hits("hack/a.sh", "set -e"), [])
        self.assertEqual(hits("hack/run", "#!/usr/bin/env python3"), [])
        self.assertEqual(hits("pkg/a.go", "package a"), ["executable bit set"])

    def test_doc_change_hint(self):
        files = rh.parse_diff(diff_of("docs/reviewer-guide.md", "@@ -1 +1 @@\n-a\n+b\n"))
        hints = rh.consistency_hints(files, set(), {})
        self.assertTrue(any("convention docs" in h for h in hints))

    def test_api_paths(self):
        api = ["staging/src/kubevirt.io/api/core/v1/types.go", "pkg/apis/v1/types.go", "api/a.go"]
        api.append("staging/src/kubevirt.io/containerized-data-importer-api/types.go")
        other = ["pkg/openapi/a.go", "pkg/api-docs/a.md", "pkg/rapid/a.go", "pkg/virt-api/a.go"]
        self.assertTrue(all(rh.API_PATH.search(p) for p in api))
        self.assertFalse(any(rh.API_PATH.search(p) for p in other))

    def test_api_change_skips_generated_dir_hint(self):
        change = "@@ -1 +1 @@\n-a\n+b\n"
        files = rh.parse_diff(diff_of("pkg/c/zz_generated.go", change))
        self.assertTrue(rh.consistency_hints(files, {"pkg/c/zz_generated.go"}, {}))
        files += rh.parse_diff(diff_of("pkg/apis/v1/types.go", change))
        self.assertEqual(rh.consistency_hints(files, {"pkg/c/zz_generated.go"}, {}), [])


